#!/usr/bin/env node
'use strict';

/**
 * Generates `apps/api/src/v3/openapi.generated.d.ts` — TypeScript types for the
 * v3 request and response bodies — from the API's OpenAPI document, which
 * Fastify builds from the JSON Schemas in `apps/api/src/v3/schemas.js` (the
 * single source). The document is built in-process with `buildApp` (memory
 * store), so no server or network is needed. `apps/api/src/v3/types.d.ts`
 * names the shapes the handlers use.
 *
 *   node gen-v3-types.js [--check]
 *
 * `--check` writes nothing and exits 1 when the file is out of date.
 */
const fs = require('node:fs');
const path = require('node:path');
const { buildApp } = require('../apps/api/src/app');
const { loadConfig } = require('../apps/api/src/config');
const { MemoryStore } = require('../apps/api/src/store/memory');

const OUT = path.join(__dirname, '..', 'apps', 'api', 'src', 'v3', 'openapi.generated.d.ts');
const HEADER = '// Generated by `npm run gen:types` from the v3 OpenAPI document (apps/api/src/v3/schemas.js). Do not edit.\n\n';

async function openapiDocument() {
  const app = buildApp({ store: new MemoryStore(), config: loadConfig({ RDS_AGENT_TOKENS: 'gen-types', RDS_PLUGIN_TOKENS: 'gen-types-plugin' }) });
  try {
    const res = await app.inject({ method: 'GET', url: '/v3/openapi.json' });
    if (res.statusCode !== 200) throw new Error(`GET /v3/openapi.json answered ${res.statusCode}`);
    return res.json();
  } finally {
    await app.close();
  }
}

async function main(argv) {
  const { default: openapiTS, astToString } = await import('openapi-typescript');
  const output = HEADER + astToString(await openapiTS(await openapiDocument()));
  const rel = path.relative(process.cwd(), OUT);
  if (argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== output) {
      process.stderr.write(`${rel} is out of date with apps/api/src/v3/schemas.js; run \`npm run gen:types\` and commit it.\n`);
      return 1;
    }
    process.stdout.write(`${rel} is current.\n`);
    return 0;
  }
  fs.writeFileSync(OUT, output);
  process.stdout.write(`Wrote ${rel}\n`);
  return 0;
}

main(process.argv.slice(2)).then(code => { process.exitCode = code; }, err => { process.stderr.write(`${err.stack || err}\n`); process.exitCode = 1; });
