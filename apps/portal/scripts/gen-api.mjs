#!/usr/bin/env node
// Writes src/api/schema.d.ts from the API's OpenAPI document, built in-process with the
// memory store (like scripts/gen-commands.js), so no server or network is needed.
// `--check` fails when the committed file is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const require = createRequire(import.meta.url);
const { buildApp } = require('../../api/src/app');
const { loadConfig } = require('../../api/src/config');
const { MemoryStore } = require('../../api/src/store/memory');

const OUT = fileURLToPath(new URL('../src/api/schema.d.ts', import.meta.url));
const HEADER = '// Generated by `npm run gen:api` from the v3 OpenAPI document. Do not edit.\n\n';

async function openapiDocument() {
  const app = buildApp({
    store: new MemoryStore(),
    config: loadConfig({ RDS_AGENT_TOKENS: 'gen-api', RDS_PLUGIN_TOKENS: 'gen-api-plugin' }),
  });
  try {
    const res = await app.inject({ method: 'GET', url: '/v3/openapi.json' });
    if (res.statusCode !== 200) throw new Error(`GET /v3/openapi.json answered ${res.statusCode}`);
    return res.json();
  } finally {
    await app.close();
  }
}

const doc = await openapiDocument();
const output = HEADER + astToString(await openapiTS(doc));

if (process.argv.includes('--check')) {
  let current;
  try {
    current = readFileSync(OUT, 'utf8');
  } catch {
    current = '';
  }
  if (current !== output) {
    console.error('src/api/schema.d.ts is out of date with the API; run `npm run gen:api` in apps/portal and commit it.');
    process.exit(1);
  }
  console.log('src/api/schema.d.ts is current.');
} else {
  writeFileSync(OUT, output);
  console.log(`Wrote ${OUT}`);
}
